export function normalizeCoreAnswers(rawAnswers = {}) {
  const answers = {
    ...rawAnswers,
    mainScreen: { ...(rawAnswers.mainScreen || {}) },
    dataSafety: { ...(rawAnswers.dataSafety || {}) }
  };
  const filled = (value) => (Array.isArray(value) ? value.length > 0 : hasValue(value));
  const fallback = (value, substitute) => (filled(value) ? value : substitute);

  answers.successEvidence = fallback(answers.successEvidence, answers.firstVersionGoal);
  answers.cannotCollect = fallback(answers.cannotCollect, '没提到的个人信息一律不收集');
  answers.aiMustNotAdd = fallback(answers.aiMustNotAdd, Array.isArray(answers.wontDo) ? [...answers.wontDo] : answers.wontDo);
  answers.mainScreen.name = fallback(answers.mainScreen.name, '首页');
  answers.mainScreen.userGoal = fallback(answers.mainScreen.userGoal, answers.userCanDo);
  answers.mainScreen.loading = fallback(answers.mainScreen.loading, '正在处理，请稍等。');
  answers.mainScreen.empty = fallback(answers.mainScreen.empty, '第一次来还没有内容，从第一步开始就行。');
  answers.mainScreen.error = fallback(answers.mainScreen.error, '刚才没做好，内容还在，可以再试一次。');
  answers.mainScreen.success = fallback(answers.mainScreen.success, '已经做好了。');
  answers.mainScreen.permissionDenied = fallback(answers.mainScreen.permissionDenied, '不涉及');
  answers.dataSafety.doesNotCollect = fallback(answers.dataSafety.doesNotCollect, '除了上面说的，其他个人信息一律不收集');
  answers.dataSafety.retention = fallback(answers.dataSafety.retention, '清掉就是真的清掉，不保留副本');
  return answers;
}

export function runInterview(targetDir, rawAnswers, options = {}) {
  const focusedIntake = focusedIntakeFrom(rawAnswers);
  if (focusedIntake) {
    const outputPath = path.join(targetDir, '.jumao', 'intake-answers.json');
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, `${JSON.stringify({
      schemaVersion: 1,
      mode: focusedIntake.mode,
      answers: focusedIntake.answers,
      updatedAt: new Date().toISOString()
    }, null, 2)}\n`, 'utf8');
    return writeFocusedPlanningWorkspace(targetDir, focusedIntake, ['.jumao/intake-answers.json']);
  }

  const force = options.force === true;
  const filledFiles = filledCoreFiles(targetDir);

  if (!force && filledFiles.length > 0) {
    return {
      ok: false,
      message: `Core files already have valid content: ${filledFiles.join(', ')}. Re-run with --force to overwrite.`
    };
  }

  const answers = normalizeCoreAnswers(rawAnswers);
  const files = renderCoreFiles(answers);
  for (const [file, text] of Object.entries(files)) {
    const fullPath = path.join(targetDir, file);
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, text, 'utf8');
  }

  return {
    ok: true,
    writtenFiles: Object.keys(files),
    strictResult: validateStrictWorkspace(targetDir)
  };
}

function writeFocusedPlanningWorkspace(targetDir, focusedIntake, writtenFiles) {
  const skippedFiles = [];
  const writeGenerated = (file, text) => {
    const fullPath = path.join(targetDir, file);
    if (fs.existsSync(fullPath)) {
      const existing = fs.readFileSync(fullPath, 'utf8').trim();
      if (existing && !existing.includes(generatedMarker)) {
        skippedFiles.push(file);
        return;
      }
    }
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, text, 'utf8');
    writtenFiles.push(file);
  };

  const agentsPath = path.join(targetDir, 'AGENTS.md');
  if (!fs.existsSync(agentsPath)) {
    fs.copyFileSync(path.join(rootDir, 'AGENTS.md'), agentsPath);
    writtenFiles.push('AGENTS.md');
  } else {
    skippedFiles.push('AGENTS.md');
  }

  if (focusedIntake.mode === 'new_project') {
    const answers = focusedIntake.answers;
    writeGenerated('product/product-brief.md', renderFocusedProductBrief(answers));
    writeGenerated('product/scope-gate.md', renderFocusedScopeGate(answers));
    writeGenerated('product/screen-states.md', renderFocusedScreenStates(answers));
    writeGenerated('product/data-safety.md', renderFocusedDataSafety());
    writeGenerated('tasks/codex-task-pack.md', renderFocusedCodexTaskPack(answers));
  } else {
    const answers = focusedIntake.answers;
    const workspaceContext = existingWorkspaceContext(targetDir);
    writeGenerated('changes/current-change.md', renderExistingChangeBrief(answers, workspaceContext));
    writeGenerated('tasks/codex-change-task-pack.md', renderExistingChangeTaskPack(answers, workspaceContext));
  }

  return {
    ok: true,
    intakeOnly: true,
    mode: focusedIntake.mode,
    writtenFiles,
    skippedFiles
  };
}

