export async function collectFocusedInterviewAnswers(targetDir, input = defaultInput, output = defaultOutput) {
  const reader = createLineReader(input, output);
  try {
    const mode = await focusedModeFor(targetDir, reader, output);
    if (!mode.ok) return mode;
    const isNew = mode.value === 'new';
    const questions = isNew ? focusedInterviewQuestions.newProject : focusedInterviewQuestions.existingProject;
    output.write(isNew
      ? '\n新项目只需要回答下面几道普通问题。\n\n'
      : '\n已有项目只需要说清楚这一件事。\n\n');
    const collected = {};
    for (const question of questions) {
      const answer = await askFocusedQuestion(reader, output, question);
      if (!answer.ok) return answer;
      collected[question.key] = answer.value;
    }
    return {
      ok: true,
      answers: isNew ? { newProject: collected } : { existingProject: collected }
    };
  } finally {
    reader.close();
  }
}

async function focusedModeFor(targetDir, reader, output) {
  const inspection = inspectWorkspace(targetDir);
  const kind = inspection.ok ? inspection.result?.workspaceKind : 'new';
  if (kind === 'existing') return { ok: true, value: 'existing' };
  if (kind === 'empty' || kind === 'new') return { ok: true, value: 'new' };
  output.write('这个文件夹准备用来做什么？\n');
  output.write('  1) 我要在这里做一个新项目\n');
  output.write('  2) 我要修改这个文件夹里的项目\n');
  for (let attempt = 0; attempt < 2; attempt += 1) {
    const raw = await reader.ask('请输入 1 或 2：');
    if (raw === null) return { ok: false, message: '回答中断了，先想好再重新运行。' };
    if (raw.trim() === '1') return { ok: true, value: 'new' };
    if (raw.trim() === '2') return { ok: true, value: 'existing' };
    if (attempt === 0) output.write('没认出来，输入数字 1 或 2 就行。\n');
  }
  return { ok: false, message: '还没告诉橘猫这个文件夹的用途，先想好再重新运行。' };
}

export function createLineReader(input, output) {
  const rl = createInterface({ input, output });
  const bufferedLines = [];
  const waiters = [];
  let closed = false;
  rl.on('line', (line) => {
    const waiter = waiters.shift();
    if (waiter) waiter(line);
    else bufferedLines.push(line);
  });
  rl.on('close', () => {
    closed = true;
    while (waiters.length > 0) waiters.shift()(null);
  });
  return {
    ask(prompt) {
      output.write(prompt);
      if (bufferedLines.length > 0) return Promise.resolve(bufferedLines.shift());
      if (closed) return Promise.resolve(null);
      return new Promise((resolve) => waiters.push(resolve));
    },
    close() {
      rl.close();
    }
  };
}

async function askFocusedQuestion(reader, output, question) {
  output.write(`${question.title}\n`);
  if (question.hint) output.write(`（${question.hint}）\n`);
  if (question.example) output.write(`（${question.example}）\n`);
  if (question.options) {
    question.options.forEach((option, index) => output.write(`  ${index + 1}) ${option}\n`));
  }
  for (let attempt = 0; attempt < 2; attempt += 1) {
    const line = await reader.ask('> ');
    if (line === null) return { ok: false, message: '回答中断了，先想好再重新运行。' };
    const raw = line.trim();
    if (question.options) {
      const byNumber = raw !== '' && /^\d+$/.test(raw) ? question.options[Number(raw) - 1] : undefined;
      const byText = question.options.find((option) => option === raw);
      const picked = byNumber || byText;
      if (picked) return { ok: true, value: picked };
      if (attempt === 0) output.write('输入选项前面的数字就行。\n');
      continue;
    }
    if (raw) return { ok: true, value: raw };
    if (question.optional) return { ok: true, value: '' };
    if (attempt === 0) output.write('这道题需要先回答一下，橘猫才能继续。\n');
  }
  return { ok: false, message: `「${question.title}」还没有回答，先想好再重新运行。` };
}

export async function collectInterviewAnswers(input = defaultInput, output = defaultOutput) {
  const reader = createLineReader(input, output);
  try {
    const answers = {};
    for (const question of orderedInterviewQuestions(interviewSchema)) {
      const promptLines = [`${question.title}`];
      if (question.description) promptLines.push(`（${question.description}）`);
      if (question.guidance) promptLines.push(`（${question.guidance}）`);
      if (question.example) promptLines.push(`（例如：${question.example}）`);
      if (!question.required) promptLines.push('（想不到可以直接回车跳过）');
      const firstLine = await reader.ask(`${promptLines.join('\n')}\n> `);
      if (firstLine === null) return { __aborted: true, message: '回答中断了，先想好再重新运行。' };
      let value = firstLine.trim();
      if (question.required && !value) {
        const secondLine = await reader.ask('这道题需要先回答一下，橘猫才能继续。\n> ');
        value = secondLine === null ? '' : secondLine.trim();
        if (!value) {
          return { __aborted: true, message: `「${question.title}」还没有回答，先想好再重新运行。` };
        }
      }
      setAnswerAtPath(
        answers,
        question.answerPath,
        question.inputType === 'list' ? splitList(value) : value
      );
    }
    return answers;
  } finally {
    reader.close();
  }
}

export function orderedInterviewQuestions(schema) {
  const stageOrder = new Map(schema.stages?.map((stage) => [stage.id, stage.order]) ?? []);
  const fallbackStageID = schema.stages?.[0]?.id;
  return [...schema.questions].sort((left, right) => {
    const leftStageOrder = stageOrder.get(left.stage ?? fallbackStageID) ?? Number.MAX_SAFE_INTEGER;
    const rightStageOrder = stageOrder.get(right.stage ?? fallbackStageID) ?? Number.MAX_SAFE_INTEGER;
    return leftStageOrder - rightStageOrder || left.order - right.order;
  });
}

